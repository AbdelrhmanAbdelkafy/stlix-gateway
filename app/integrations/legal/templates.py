TEMPLATES: tuple[Template, ...] = (
    EMPLOYMENT, NDA, IMPORT_PURCHASE, SUPPLY, NOTICE, BOARD_RESOLUTION)
BY_KEY = {t.key: t for t in TEMPLATES}

_PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")


def as_dicts() -> list[dict]:
    return [{"key": t.key, "title": t.title, "summary": t.summary,
             "governed_by": list(t.governed_by), "clauses": len(t.clauses),
             "fields": [{"key": f.key, "label": f.label, "example": f.example,
                         "required": f.required} for f in t.fields],
             "check": list(t.check)}
            for t in TEMPLATES]


def render(key: str, values: dict[str, str], include_optional: bool = False) -> dict:
    """Fill a template. Unfilled blanks stay visible as `⟨label⟩`.

    They are never quietly dropped: a contract that reads complete while a party
    name or a delivery date silently vanished is worse than one with an obvious
    hole in it.
    """
    t = BY_KEY.get(key)
    if t is None:
        raise KeyError(key)
    labels = {f.key: f.label for f in t.fields}
    missing: list[str] = []

    def sub(m: re.Match) -> str:
        k = m.group(1)
        v = (values.get(k) or "").strip()
        if v:
            return v
        label = labels.get(k, k)
        if k not in missing:
            missing.append(k)
        return f"⟨{label}⟩"

    parts = [f"# {t.title}", ""]
    used: list[dict] = []
    for i, c in enumerate(t.clauses, 1):
        if c.optional and not include_optional:
            continue
        body = _PLACEHOLDER.sub(sub, c.body)
        parts += [f"## {i}. {c.heading}", "", body, ""]
        used.append({"heading": c.heading, "basis": c.basis, "optional": c.optional})

    required_missing = [k for k in missing
                        if next((f.required for f in t.fields if f.key == k), True)]
    return {
        "key": t.key, "title": t.title,
        "markdown": "\n".join(parts).strip() + "\n",
        "clauses": used,
        "governed_by": list(t.governed_by),
        "missing_fields": [{"key": k, "label": labels.get(k, k)} for k in missing],
        "required_missing": required_missing,
        "check": list(t.check),
        "disclaimer": (
            "دي **مسودة** مبنية على هيكل بنود، مش رأي قانوني ولا بديل عن محامٍ. "
            "مافيش بند هنا بيستشهد برقم مادة — أرقام المواد بتتقال بس من نصّ قانون "
            "محمّل في corpus/legal، وبيتحقق منها الحارس."),
    }
