"""Contract skeletons the counsel can draft from.

These are structures, not opinions: the clauses a given agreement is expected to
contain, in the order Egyptian practice puts them, with the blanks named.

**No clause here cites an article.** Naming the governing law is safe and
useful — «ده محكوم بقانون العمل» is true and checkable. Naming *مادة 47 من
قانون العمل* from memory is the same failure `citations.py` exists to catch,
and writing it into a template would smuggle it past that guard, since a
template is not model output. Where a clause depends on a statutory limit — a
notice period, a penalty cap, a probation length — the template says so and
leaves the number as a blank for the loaded text (or a lawyer) to fill.

Each template ends with `check`: what a human has to confirm before this is
signed. A generated contract that arrives without that list reads finished, and
that is the wrong impression to leave a non-lawyer with.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Field:
    key: str
    label: str
    example: str = ""
    required: bool = True


@dataclass(frozen=True)
class Clause:
    heading: str
    body: str
    #: Why this clause is here / what governs it. Shown beside the clause.
    basis: str = ""
    optional: bool = False


@dataclass(frozen=True)
class Template:
    key: str
    title: str
    summary: str
    governed_by: tuple[str, ...]          # manifest slugs
    fields: tuple[Field, ...]
    clauses: tuple[Clause, ...]
    check: tuple[str, ...] = field(default_factory=tuple)


